describe("SPARE8 independent pending inventory", () => {
  it("J8-OFF-PENDING OFF stops a visible unclaimed refill after its create answer was lost", async () => {
    const h = await start("j8-off-pending");
    const { s1 } = await seed(h);
    let refillId: string | undefined;
    vi.stubGlobal("fetch", async (input: unknown, init: RequestInit = {}) => {
      const url = new URL(String(input));
      if (!refillId && init.method === "POST" && url.pathname.endsWith("/sandboxes")
          && JSON.parse(String(init.body)).labels.purpose === "spare") {
        const accepted = await h.boat.fetch(input, init);
        refillId = (await accepted.json()).sandbox.id;
        throw Object.assign(new Error("J8 accepted refill, answer lost"), { code: "ETIMEDOUT" });
      }
      return h.boat.fetch(input, init);
    });
    expect((await settle(h.acquire("j8-claim"))).providerLeaseId).toBe(s1);
    await until(() => !!refillId, "accepted refill");
    await advance(3_000);
    const pending = h.boat.boxes.get(refillId!)!;
    expect(pending.name).toBe("");
    expect(h.boat.liveSpares()).toEqual([refillId]);
    h.config.spares = 0;
    const at = h.boat.mark("OFF with visible unresolved refill");
    await advance(5 * TICK_MS);
    const stops = h.boat.log.filter(e => e.seq > at && e.method === "POST" && e.path === `/sandboxes/${refillId}/stop`);
    console.log("J8 pending OFF", JSON.stringify({refillId, state: pending.state, stops: stops.length,
      pending: h.state.get(`${h.company}:pending-refills`), live: h.boat.liveSpares()}));
    expect(stops, "OFF must not hide a billed box merely because its create answer was lost").toHaveLength(1);
    expect(h.boat.liveSpares()).toEqual([]);
  });
});
