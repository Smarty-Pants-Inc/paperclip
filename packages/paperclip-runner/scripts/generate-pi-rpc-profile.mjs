import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PI_DISTRIBUTION_CLOSURE_SHA256 } from "../src/drivers/acpx/pi-closure-pins.ts";
import { PI_NODE_VERSION } from "../src/drivers/acpx/pi-node-pins.ts";

// Same upstream-only closure attestation as acpx-release-attestations.mjs:67-79.
// The native identity is distinct: no ACPX version or pi-acp transport.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = async path => JSON.parse(await readFile(resolve(root, path), "utf8"));
const declaration = await read("pi-rpc-profile.json");
const lock = await read("scripts/pi-distribution/package-lock.json");
if (declaration.driverKind !== "pi_rpc" || declaration.protocolVersion !== 1
  || declaration.profileVersion !== 1 || declaration.runtimePackage !== "@earendil-works/pi-coding-agent"
  || lock.packages[`node_modules/${declaration.runtimePackage}`]?.version !== declaration.runtimeVersion) {
  throw new Error("Native Pi profile differs from its pinned distribution");
}
const canonical = value => value && typeof value === "object"
  ? Array.isArray(value) ? value.map(canonical) : Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])]))
  : value;
const release = { ...declaration, nodeVersion: PI_NODE_VERSION, closure: PI_DISTRIBUTION_CLOSURE_SHA256 };
const commandDigest = `sha256:${createHash("sha256").update(JSON.stringify(canonical(release))).digest("hex")}`;
const profile = { ...declaration, commandDigest };
const outputs = {
  "src/drivers/pi/generated-profile.ts": `// Generated by scripts/generate-pi-rpc-profile.mjs. Do not edit.\nexport const QUALIFIED_PI_RPC_PROFILE = ${JSON.stringify(profile, null, 2)} as const;\n`,
  "runner/crates/runner-core/src/generated_pi_rpc_profile.rs": `// Generated by scripts/generate-pi-rpc-profile.mjs. Do not edit.\npub const PI_RPC_VERSION: &str = ${JSON.stringify(declaration.runtimeVersion)};\npub const PI_RPC_PROFILE_JSON: &str = r#"${JSON.stringify(profile)}"#;\n`,
  "protocol/provider-schemas/pi-rpc-profile.schema.json": JSON.stringify({
    $schema: "https://json-schema.org/draft/2020-12/schema", $id: "paperclip.pi-rpc-profile.v1", type: "object",
    additionalProperties: false, required: Object.keys(profile),
    properties: Object.fromEntries(Object.entries(profile).map(([key, value]) => [key, { const: value }])),
  }, null, 2) + "\n",
};
for (const [path, content] of Object.entries(outputs)) {
  const target = resolve(root, path);
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8").catch(() => "") !== content) throw new Error(`Stale native Pi binding: ${path}; run generate:pi-rpc-profile`);
  } else await writeFile(target, content);
}
console.log(`Native Pi RPC profile ${declaration.runtimeVersion}: ${commandDigest}`);
