// @vitest-environment jsdom

import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { act, forwardRef, useImperativeHandle, type ReactNode } from "react";
import { flushSync } from "react-dom";
import { createRoot, type Root } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { HeartbeatRun, IssueComment, IssueQueuedCommentQueue } from "@paperclipai/shared";
import { ThemeProvider } from "@/context/ThemeContext";
import { TooltipProvider } from "@/components/ui/tooltip";
import { MemoryRouter } from "@/lib/router";
import { TaskChatThread } from "../TaskChatThread";
import { TaskChatRunnerHeader } from "./TaskChatRunnerTurn";
import capturedRows from "./fixtures/resume-gap-real-route.json";

// Keep (PERSON CASE, merged line, RFL 11:06Z): after a person presses Resume on a paused agent the thread never
// keeps saying '<agent> is paused'. From the Resume until the message's run header exists the ONE line is the
// 'resuming' note; then the header replaces it: never two lines, never none.
// Only auxiliary data / editor machinery are replaced. The actual thread, the queued panel, the run header and
// their display conditions are rendered unchanged, at 1440 and 390.
const viewport = vi.hoisted(() => ({ mobile: false }));
vi.mock("@/context/SidebarContext", () => ({ useSidebar: () => ({ isMobile: viewport.mobile }) }));
vi.mock("@/context/CompanyContext", () => ({ useOptionalCompany: () => null, useCompany: () => ({ selectedCompany: null, selectedCompanyId: null, companies: [], loading: false }) }));
vi.mock("@/hooks/useCoordinatorWorkspaceEnabled", () => ({ useCoordinatorWorkspaceEnabled: () => ({ enabled: false, loaded: true, userId: "rgap-person" }) }));
vi.mock("@/hooks/useStreamlinedUiEnabled", () => ({ useStreamlinedUiEnabled: () => ({ enabled: true, loaded: true }) }));
vi.mock("@/hooks/useIssuePlanDocument", () => ({ useIssuePlanDocument: () => ({ data: null }) }));
vi.mock("@/components/transcript/useLiveRunTranscripts", () => ({ useLiveRunTranscripts: () => ({ transcriptByRun: new Map(), isInitialHydrating: false }) }));
vi.mock("@/components/transcript/useNativeRunTranscripts", () => ({ useNativeRunTranscripts: () => ({ transcriptByRun: new Map(), errorsByRun: new Map(), terminalHydratedRunIds: new Set() }) }));
vi.mock("@/components/MarkdownEditor", () => ({ MarkdownEditor: forwardRef(function Editor(_props, ref) {
  useImperativeHandle(ref, () => ({ insertMarkdown() {}, focus() {} }));
  return <div data-testid="editor-machinery-not-under-test" />;
}) }));

type State = "resuming" | "resuming-lock-held" | "waiting-behind" | "header" | "working";
type Sample = { variant: "ordinary" | "lock" | "busy"; state: State; ms: number; lifecycleState: string; messageId: string; noteId: string;
  readAt: string; comments: IssueComment[]; queue: IssueQueuedCommentQueue;
  run: Pick<HeartbeatRun, "id" | "status" | "execution" | "createdAt" | "startedAt"> | null };
// Fixture provenance: server/src/__tests__/resume-gap-true-line.test.ts writes these exact GET bodies (GET
// /issues/:id/comments, /issues/:id/queued-comments, /issues/:id/live-runs) after the REAL Pause, comment and
// Resume routes under the real workers and timers. To refresh: set RGAP_CAPTURE_DIR for that suite, then point
// RGAP_ROW_INPUT at its JSON here. The checked-in snapshot is generated by that command, never hand-written.
const samples = (process.env.RGAP_ROW_INPUT
  ? JSON.parse(readFileSync(process.env.RGAP_ROW_INPUT, "utf8")) : capturedRows) as unknown as Sample[];
// Literals, independent of the production constants.
const RESUMING = "Managed Pi is resuming. Your message is saved and will start when Managed Pi is ready.";
const WORKING = "Managed Pi is working on your message.";
const rendered: unknown[] = [];
const count = (text: string | null | undefined, needle: string) => (text ?? "").split(needle).length - 1;

describe("Resume -> 'resuming' -> the run header: the rendered real GET rows (TaskChatThread)", () => {
  let container: HTMLDivElement, root: Root, query: QueryClient;
  beforeEach(() => {
    container = document.createElement("div"); document.body.appendChild(container); root = createRoot(container);
    query = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  });
  afterEach(() => {
    flushSync(() => root.unmount()); query.clear(); container.remove(); vi.useRealTimers(); vi.restoreAllMocks();
    if (process.env.RGAP_RENDER_DIR) {
      mkdirSync(process.env.RGAP_RENDER_DIR, { recursive: true });
      writeFileSync(path.join(process.env.RGAP_RENDER_DIR, "resume-gap-rendered-rows.json"), JSON.stringify(rendered, null, 2) + "\n");
    }
  });
  function render(children: ReactNode) {
    act(() => root.render(<MemoryRouter><QueryClientProvider client={query}><ThemeProvider><TooltipProvider>{children}</TooltipProvider></ThemeProvider></QueryClientProvider></MemoryRouter>));
  }

  it("has the real-route evidence for every state of the case, in all three rows", () => {
    for (const variant of ["ordinary", "lock", "busy"]) {
      const states = new Set(samples.filter(row => row.variant === variant).map(row => row.state));
      expect(states.has("resuming"), `${variant}: resuming`).toBe(true);
      expect(states.has("working"), `${variant}: working`).toBe(true);
    }
    expect(samples.some(row => row.variant === "lock" && row.state === "resuming-lock-held" && row.ms > 3_000)).toBe(true);
    expect(samples.some(row => row.variant === "busy" && row.state === "waiting-behind")).toBe(true);
  });

  for (const width of [1440, 390]) for (const [index, row] of samples.entries()) {
    it(`#${index} ${row.variant} ${row.state} (+${row.ms} ms) at ${width}: exactly the ONE true line`, async () => {
      Object.defineProperty(window, "innerWidth", { configurable: true, value: width }); viewport.mobile = width < 768;
      container.style.width = `${width}px`;
      vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date(row.readAt));
      const comments = row.comments.map(comment => ({ ...comment, createdAt: new Date(comment.createdAt), updatedAt: new Date(comment.updatedAt) }));
      const run = row.run;
      render(<>
        <TaskChatThread comments={comments} onAdd={async () => {}} conversationMode conversationOwnerId="rgap-person"
          currentUserId="rgap-person" issueStatus="in_progress" queuedCommentQueue={row.queue} queuedMessageAutoSteerDelayMs={null} />
        {run && (run.status === "queued" || run.status === "running") ? <TaskChatRunnerHeader runId={run.id} agentName="Managed Pi"
          status={run.status} execution={run.execution} startedAtMs={new Date(run.startedAt ?? run.createdAt).getTime()} /> : null}
      </>);
      await act(async () => {});
      const text = container.textContent ?? "";
      const panelLines = [...container.querySelectorAll('[data-testid="task-chat-queued-messages"] p[role="status"]')].map(node => node.textContent);
      const header = container.querySelector('[data-testid="task-chat-runner-identity-row"]')?.textContent ?? null;
      rendered.push({ index, variant: row.variant, state: row.state, ms: row.ms, width, panelLines, header, domText: text });
      expect(text, "the person's message is on the thread").toContain("M: are you there?");
      expect(text, "a retired note leaves no trace").not.toMatch(/deleted/i);
      expect(count(text, "is paused"), "never the stale paused note after Resume").toBe(0);
      expect(count(text, "is resumed")).toBe(0);
      expect(text).not.toMatch(/wasn't answered|no run started|without a reply|Sending it again/);
      expect(panelLines).toEqual([]);
      if (row.state === "resuming" || row.state === "resuming-lock-held") {
        // The ONE line: the resuming note. No run header, no working note beside it.
        expect(count(text, RESUMING)).toBe(1);
        expect(text).toContain("Managed Pi is resuming");
        expect(header, "no run header beside the resuming line").toBeNull();
        expect(count(text, WORKING)).toBe(0);
        expect(text, "nothing for the person to do while it resumes").not.toMatch(/Next action/);
      }
      if (row.state === "waiting-behind") {
        // The ONE line: the queued run's header. The resuming note is gone.
        expect(header).toContain("Waiting for Managed Pi");
        expect(count(text, "Waiting for Managed Pi")).toBe(1);
        expect(count(text, "is resuming")).toBe(0);
        expect(count(text, WORKING)).toBe(0);
      }
      if (row.state === "header") {
        expect(header, "the run's header is the one line").not.toBeNull();
        expect(count(text, "is resuming")).toBe(0);
        expect(count(text, WORKING)).toBe(0);
      }
      if (row.state === "working") {
        expect(count(text, WORKING)).toBe(1);
        expect(count(text, "is resuming")).toBe(0);
      }
    });
  }
});
