// @vitest-environment jsdom

import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { act, forwardRef, useImperativeHandle, type ReactNode } from "react";
import { flushSync } from "react-dom";
import { createRoot, type Root } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { HeartbeatRun, IssueComment, IssueQueuedCommentQueue } from "@paperclipai/shared";
import { ThemeProvider } from "@/context/ThemeContext";
import { TooltipProvider } from "@/components/ui/tooltip";
import { MemoryRouter } from "@/lib/router";
import { TaskChatThread } from "../TaskChatThread";
import { TaskChatQueuedMessages } from "./TaskChatQueuedMessages";
import { TaskChatRunnerHeader } from "./TaskChatRunnerTurn";
import capturedRows from "./fixtures/execution-wait-real-route.json";

// Only auxiliary data / editor machinery are replaced. The actual thread,
// queued panel, run header and their display conditions are rendered unchanged.
const viewport = vi.hoisted(() => ({ mobile: false }));
vi.mock("@/context/SidebarContext", () => ({ useSidebar: () => ({ isMobile: viewport.mobile }) }));
vi.mock("@/context/CompanyContext", () => ({ useOptionalCompany: () => null, useCompany: () => ({ selectedCompany: null, selectedCompanyId: null, companies: [], loading: false }) }));
vi.mock("@/hooks/useCoordinatorWorkspaceEnabled", () => ({ useCoordinatorWorkspaceEnabled: () => ({ enabled: false, loaded: true, userId: "m10-person" }) }));
vi.mock("@/hooks/useStreamlinedUiEnabled", () => ({ useStreamlinedUiEnabled: () => ({ enabled: true, loaded: true }) }));
vi.mock("@/hooks/useIssuePlanDocument", () => ({ useIssuePlanDocument: () => ({ data: null }) }));
vi.mock("@/components/transcript/useLiveRunTranscripts", () => ({ useLiveRunTranscripts: () => ({ transcriptByRun: new Map(), isInitialHydrating: false }) }));
vi.mock("@/components/transcript/useNativeRunTranscripts", () => ({ useNativeRunTranscripts: () => ({ transcriptByRun: new Map(), errorsByRun: new Map(), terminalHydratedRunIds: new Set() }) }));
vi.mock("@/components/MarkdownEditor", () => ({ MarkdownEditor: forwardRef(function Editor(_props, ref) {
  useImperativeHandle(ref, () => ({ insertMarkdown() {}, focus() {} }));
  return <div data-testid="editor-machinery-not-under-test" />;
}) }));

type Sample = {
  producer: string; surface: "task" | "chat"; reason: string; elapsed: number; readAt: string;
  expectedLine?: string; messageId: string; queue?: IssueQueuedCommentQueue; comments: IssueComment[]; run?: HeartbeatRun;
};
// Fixture provenance: execution-wait-one-line-routes.test.ts writes these exact
// GET bodies after real comment admission / Stop / pause. To refresh, set
// M10_CAPTURE_DIR for that suite, then point M10_ROW_INPUT at its JSON here.
// The checked-in snapshot is generated by that command, never hand-written.
const samples = (process.env.M10_ROW_INPUT
  ? JSON.parse(readFileSync(process.env.M10_ROW_INPUT, "utf8")) : capturedRows) as unknown as Sample[];
const deferred = samples.filter(row => row.queue && row.expectedLine);
const queued = samples.filter(row => row.reason === "queued_run");
const rendered: unknown[] = [];

describe("SUPERSEDE-WAITNOTE-UPSTREAM-HEADER-1119 rendered real GET rows", () => {
  let container: HTMLDivElement, root: Root, query: QueryClient;
  beforeEach(() => {
    container = document.createElement("div"); document.body.appendChild(container); root = createRoot(container);
    query = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  });
  afterEach(() => {
    flushSync(() => root.unmount()); query.clear(); container.remove(); vi.useRealTimers(); vi.restoreAllMocks();
    if (process.env.M10_RENDER_DIR) {
      mkdirSync(process.env.M10_RENDER_DIR, { recursive: true });
      writeFileSync(path.join(process.env.M10_RENDER_DIR, "rendered-rows.json"), JSON.stringify(rendered, null, 2) + "\n");
    }
  });
  function render(children: ReactNode) {
    act(() => root.render(<MemoryRouter><QueryClientProvider client={query}><ThemeProvider><TooltipProvider>{children}</TooltipProvider></ThemeProvider></QueryClientProvider></MemoryRouter>));
  }

  it("has real-route evidence for every deferred reason and both surfaces", () => {
    expect(new Set(deferred.map(row => row.reason))).toEqual(new Set(["remote_cleanup", "execution_recovery", "execution_active", "agent.not_invokable"]));
    expect(new Set(deferred.map(row => row.surface))).toEqual(new Set(["task", "chat"]));
    expect(new Set(deferred.map(row => row.elapsed))).toEqual(new Set([10_000, 120_000, 600_000, 660_000]));
  });

  for (const width of [1440, 390]) for (const row of deferred) {
    it(`${row.surface} ${row.reason} +${row.elapsed}ms at ${width}: exactly one true panel line`, async () => {
      Object.defineProperty(window, "innerWidth", { configurable: true, value: width }); viewport.mobile = width < 768;
      container.style.width = `${width}px`;
      vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date(row.readAt));
      const comments = row.comments.map(comment => ({ ...comment, createdAt: new Date(comment.createdAt), updatedAt: new Date(comment.updatedAt) }));
      render(<TaskChatThread comments={comments} onAdd={async () => {}} conversationMode={row.surface === "chat"}
        conversationOwnerId={row.surface === "chat" ? "m10-person" : undefined} currentUserId="m10-person" issueStatus="in_progress"
        queuedCommentQueue={row.queue!} queuedMessageAutoSteerDelayMs={null} />);
      await act(async () => {});
      const pane = container.querySelector('[data-testid="task-chat-queued-messages"]');
      const status = [...(pane?.querySelectorAll('p[role="status"]') ?? [])].map(node => node.textContent);
      rendered.push({ surface: row.surface, reason: row.reason, elapsed: row.elapsed, width, status, domText: container.textContent });
      expect(status).toEqual([row.expectedLine]);
      expect(container.textContent?.split(row.expectedLine!)).toHaveLength(2);
      expect(container.textContent).not.toContain("no run started");
      if (row.reason === "remote_cleanup") expect(container.textContent).not.toContain("Waiting for the current run");
    });
  }

  for (const width of [1440, 390]) for (const row of queued) {
    it(`${row.surface} queued run +${row.elapsed}ms at ${width}: upstream header only, no queued panel note`, async () => {
      Object.defineProperty(window, "innerWidth", { configurable: true, value: width }); viewport.mobile = width < 768;
      vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date(row.readAt));
      const run = row.run!;
      render(<>
        <TaskChatRunnerHeader runId={run.id} agentName="Managed Pi" status={run.status} execution={run.execution}
          startedAtMs={new Date(run.startedAt ?? run.createdAt).getTime()} />
        <TaskChatQueuedMessages queue={row.queue!} autoSteerDelayMs={null} onEdit={() => {}} onReorder={async () => {}} onSteer={async () => {}} onDiscard={async () => {}} />
      </>);
      await act(async () => {});
      const identity = container.querySelector('[data-testid="task-chat-runner-identity-row"]');
      const expected = run.execution?.agentQueue ? "Waiting for Managed Pi" : row.elapsed < 30_000 ? "Working" : "Waiting to start";
      rendered.push({ reason: "queued_run", width, elapsed: row.elapsed, expected, domText: container.textContent });
      expect(identity?.textContent).toContain(expected);
      expect(container.textContent?.split(expected)).toHaveLength(2);
      expect(container.querySelector('[data-testid="task-chat-queued-messages"] p[role="status"]')).toBeNull();
    });
  }
});
